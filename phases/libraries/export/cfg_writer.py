"""Configuration file writer for .cfg format export."""

import os
import logging
from typing import Union, Optional
from pathlib import Path
from datetime import datetime
import shutil

from src.openproject_config_manager.core.config import Configuration


logger = logging.getLogger(__name__)


class CfgWriter:
    """Writer for OpenProject configuration files in .cfg format."""
    
    def __init__(self):
        """Initialize the configuration writer."""
        pass
    
    def write_configuration(self, 
                          configuration: Configuration,
                          output_path: Union[str, Path],
                          backup_existing: bool = True,
                          add_comments: bool = True) -> str:
        """
        Write configuration to .cfg file format.
        
        Args:
            configuration: Configuration object to export
            output_path: Path to write the configuration file
            backup_existing: Whether to backup existing file
            add_comments: Whether to add explanatory comments
            
        Returns:
            Path to the written configuration file
        """
        output_path = Path(output_path)
        
        logger.info(f"Writing configuration to {output_path}")
        
        # Create directory if it doesn't exist
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Backup existing file if requested
        if backup_existing and output_path.exists():
            self._backup_existing_file(output_path)
        
        # Generate configuration content
        if add_comments:
            config_content = self._generate_cfg_with_comments(configuration)
        else:
            config_content = configuration.to_cfg_format()
        
        # Write to file
        try:
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write(config_content)
            
            logger.info(f"Configuration successfully written to {output_path}")
            
            # Set appropriate file permissions (readable by owner/group, not world)
            os.chmod(output_path, 0o640)
            
            return str(output_path)
            
        except Exception as e:
            logger.error(f"Failed to write configuration file: {e}")
            raise
    
    def _backup_existing_file(self, file_path: Path):
        """Create a backup of existing configuration file."""
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        backup_path = file_path.with_suffix(f".{timestamp}.bak")
        
        try:
            shutil.copy2(file_path, backup_path)
            logger.info(f"Existing file backed up to {backup_path}")
        except Exception as e:
            logger.warning(f"Failed to backup existing file: {e}")
    
