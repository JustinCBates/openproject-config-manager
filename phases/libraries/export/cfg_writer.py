    def write_docker_compose_env(self, 
                                configuration: Configuration,
                                output_path: Union[str, Path]) -> str:
        """
        Write configuration as Docker Compose .env file.
        
        Args:
            configuration: Configuration object to export
            output_path: Path to write the .env file
            
        Returns:
            Path to the written .env file
        """
        output_path = Path(output_path)
        
        logger.info(f"Writing Docker Compose .env file to {output_path}")
        
        # Create directory if it doesn't exist
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        lines = []
        
        # Header
        lines.extend([
            "# Docker Compose Environment File",
            "# Generated by OpenProject Configuration Manager",
            f"# Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            "#",
            "# This file is used by docker-compose.yml to configure the OpenProject deployment",
            "",
        ])
        
        # Convert configuration to environment variables
        env_vars = self._configuration_to_env_vars(configuration)
        
        for key, value in env_vars.items():
            lines.append(f"{key}={value}")
        
        lines.append("")  # Final newline
        
        # Write to file
        try:
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write('\n'.join(lines))
            
            logger.info(f"Docker Compose .env file successfully written to {output_path}")
            
            # Set appropriate file permissions
            os.chmod(output_path, 0o640)
            
            return str(output_path)
            
        except Exception as e:
            logger.error(f"Failed to write .env file: {e}")
            raise
    
    def _configuration_to_env_vars(self, configuration: Configuration) -> dict:
        """Convert Configuration object to environment variables dictionary."""
        env_vars = {}
        
        # Core settings
        env_vars['SECRET_KEY_BASE'] = configuration.secret_key_base
        env_vars['RAILS_ENV'] = configuration.rails_env
        env_vars['RAILS_CACHE_STORE'] = configuration.rails_cache_store
        
        # Database settings
        env_vars['DATABASE_ADAPTER'] = configuration.database.adapter
        env_vars['DATABASE_HOST'] = configuration.database.host
        env_vars['DATABASE_PORT'] = str(configuration.database.port)
        env_vars['DATABASE_NAME'] = configuration.database.name
        env_vars['DATABASE_USERNAME'] = configuration.database.username
        env_vars['DATABASE_PASSWORD'] = configuration.database.password
        env_vars['DATABASE_ENCODING'] = configuration.database.encoding
        
        # Proxy settings
        env_vars['DOMAIN'] = configuration.proxy.domain
        if configuration.proxy.additional_domains:
            env_vars['ADDITIONAL_DOMAINS'] = ','.join(configuration.proxy.additional_domains)
        env_vars['SSL_ENABLED'] = str(configuration.proxy.ssl_enabled).lower()
        env_vars['LETS_ENCRYPT'] = str(configuration.proxy.lets_encrypt).lower()
        if configuration.proxy.lets_encrypt_email:
            env_vars['LETS_ENCRYPT_EMAIL'] = configuration.proxy.lets_encrypt_email
        if configuration.proxy.ssl_cert_path:
            env_vars['SSL_CERT_PATH'] = configuration.proxy.ssl_cert_path
        if configuration.proxy.ssl_key_path:
            env_vars['SSL_KEY_PATH'] = configuration.proxy.ssl_key_path
        
        # Storage settings
        env_vars['DATA_VOLUME'] = configuration.storage.data_volume
        env_vars['LOGS_VOLUME'] = configuration.storage.logs_volume
        env_vars['BACKUP_ENABLED'] = str(configuration.storage.backup_enabled).lower()
        env_vars['BACKUP_SCHEDULE'] = configuration.storage.backup_schedule
        env_vars['BACKUP_RETENTION_DAYS'] = str(configuration.storage.backup_retention_days)
        env_vars['BACKUP_LOCATION'] = configuration.storage.backup_location
        
        # Email settings
        env_vars['EMAIL_DELIVERY_METHOD'] = configuration.email_delivery_method
        if configuration.smtp_address:
            env_vars['SMTP_ADDRESS'] = configuration.smtp_address
        if configuration.smtp_port:
            env_vars['SMTP_PORT'] = str(configuration.smtp_port)
        if configuration.smtp_domain:
            env_vars['SMTP_DOMAIN'] = configuration.smtp_domain
        if configuration.smtp_user_name:
            env_vars['SMTP_USER_NAME'] = configuration.smtp_user_name
        if configuration.smtp_password:
            env_vars['SMTP_PASSWORD'] = configuration.smtp_password
        env_vars['SMTP_ENABLE_STARTTLS_AUTO'] = str(configuration.smtp_enable_starttls_auto).lower()
        
        # Cache settings
        env_vars['MEMCACHED_SERVER'] = configuration.memcached_server
        if configuration.redis_url:
            env_vars['REDIS_URL'] = configuration.redis_url
        
        # Performance settings
        env_vars['WEB_CONCURRENCY'] = str(configuration.web_concurrency)
        env_vars['WEB_TIMEOUT'] = str(configuration.web_timeout)
        env_vars['WEB_MAX_REQUESTS'] = str(configuration.web_max_requests)
        
        # Security settings
        env_vars['FORCE_SSL'] = str(configuration.force_ssl).lower()
        env_vars['SESSION_COOKIE_SECURE'] = str(configuration.session_cookie_secure).lower()
        
        # Feature settings
        env_vars['ATTACHMENTS_STORAGE'] = configuration.attachments_storage
        
        # Logging settings
        env_vars['LOG_LEVEL'] = configuration.log_level
        env_vars['RAILS_LOG_TO_STDOUT'] = str(configuration.rails_log_to_stdout).lower()
        
        # Custom variables
        env_vars.update(configuration.custom_variables)
        
        return env_vars