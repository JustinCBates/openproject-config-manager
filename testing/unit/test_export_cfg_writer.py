    def test_configuration_export_roundtrip(self, sample_configuration, temp_dir):
        """Test that configuration can be exported and re-imported."""
        writer = CfgWriter()
        cfg_file = temp_dir / "roundtrip.cfg"
        
        # Export configuration
        writer.write_configuration(
            sample_configuration, 
            cfg_file,
            add_comments=False  # Comments might interfere with parsing
        )
        
        # Re-import configuration
        imported_config = Configuration.from_cfg_file(cfg_file)
        
        # Compare key fields
        assert imported_config.secret_key_base == sample_configuration.secret_key_base
        assert imported_config.rails_env == sample_configuration.rails_env
        assert imported_config.database.adapter == sample_configuration.database.adapter
        assert imported_config.database.host == sample_configuration.database.host
        assert imported_config.database.port == sample_configuration.database.port
        assert imported_config.proxy.domain == sample_configuration.proxy.domain
        assert imported_config.proxy.ssl_enabled == sample_configuration.proxy.ssl_enabled