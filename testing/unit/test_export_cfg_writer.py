    def test_backup_existing_file(self, temp_dir):
        """Test backup of existing file."""
        writer = CfgWriter()
        original_file = temp_dir / "config.cfg"
        original_content = "# Original content"
        original_file.write_text(original_content, encoding='utf-8')
        
        with patch('shutil.copy2') as mock_copy:
            writer._backup_existing_file(original_file)
        
        # Should call copy2 with source and backup path
        mock_copy.assert_called_once()
        args = mock_copy.call_args[0]
        assert args[0] == original_file
        assert str(args[1]).endswith('.bak')
    
