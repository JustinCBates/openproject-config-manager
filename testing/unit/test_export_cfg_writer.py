    def test_configuration_to_env_vars(self, sample_configuration):
        """Test conversion of configuration to environment variables."""
        writer = CfgWriter()
        
        env_vars = writer._configuration_to_env_vars(sample_configuration)
        
        # Check core variables
        assert env_vars['SECRET_KEY_BASE'] == sample_configuration.secret_key_base
        assert env_vars['RAILS_ENV'] == sample_configuration.rails_env
        assert env_vars['DATABASE_ADAPTER'] == sample_configuration.database.adapter
        
        # Check port conversion to string
        assert env_vars['DATABASE_PORT'] == str(sample_configuration.database.port)
        
        # Check boolean conversion to lowercase string
        assert env_vars['SSL_ENABLED'] == str(sample_configuration.proxy.ssl_enabled).lower()
        assert env_vars['BACKUP_ENABLED'] == str(sample_configuration.storage.backup_enabled).lower()
        
        # Check array conversion
        if sample_configuration.proxy.additional_domains:
            assert env_vars['ADDITIONAL_DOMAINS'] == ','.join(sample_configuration.proxy.additional_domains)
        
        # Check custom variables
        if sample_configuration.custom_variables:
            for key, value in sample_configuration.custom_variables.items():
                assert env_vars[key] == value
    
