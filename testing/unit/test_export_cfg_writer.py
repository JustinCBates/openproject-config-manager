    def test_write_docker_compose_env(self, sample_configuration, temp_dir):
        """Test writing Docker Compose .env file."""
        writer = CfgWriter()
        output_path = temp_dir / "test.env"
        
        result_path = writer.write_docker_compose_env(sample_configuration, output_path)
        
        # Check that file was created
        assert Path(result_path).exists()
        assert result_path == str(output_path)
        
        # Check file content
        content = output_path.read_text(encoding='utf-8')
        assert 'SECRET_KEY_BASE=' in content
        assert 'DATABASE_ADAPTER=' in content
        assert 'DOMAIN=' in content
        
        # Should not have quotes around values in .env format
        lines = content.split('\n')
        env_lines = [line for line in lines if '=' in line and not line.startswith('#')]
        
        # Check that values are not quoted (Docker Compose .env format)
        for line in env_lines:
            if '=' in line:
                key, value = line.split('=', 1)
                # Values should not be wrapped in quotes
                assert not (value.startswith('"') and value.endswith('"'))
    
