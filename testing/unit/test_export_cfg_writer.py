    def test_write_configuration_backup_existing(self, sample_configuration, temp_dir):
        """Test configuration writing with backup of existing file."""
        writer = CfgWriter()
        output_path = temp_dir / "test_config.cfg"
        
        # Create existing file
        existing_content = "# Existing configuration"
        output_path.write_text(existing_content, encoding='utf-8')
        
        with patch('shutil.copy2') as mock_copy:
            result_path = writer.write_configuration(
                sample_configuration, 
                output_path,
                backup_existing=True
            )
        
        # Check that backup was attempted
        mock_copy.assert_called_once()
        
        # Check that new file was written
        assert Path(result_path).exists()
        content = output_path.read_text(encoding='utf-8')
        assert existing_content not in content
        assert 'SECRET_KEY_BASE=' in content
    
